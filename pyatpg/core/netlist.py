class Gate:
    def __init__(self, gtype, output, inputs):
        g = gtype.upper()
        self.gtype = g
        self.type = g
        self.output = output
        self.inputs = inputs

    def __repr__(self):
        return f"{self.gtype} {self.output} <- {self.inputs}"


class FlipFlop:
    def __init__(self, q, d):
        self.q = q
        self.d = d
        self.is_scan = False

    def __repr__(self):
        return f"DFF {self.q} <- {self.d}"

class ScanFlipFlop(FlipFlop):
    def __init__(self, q, d, si, se):
        super().__init__(q, d)
        self.si = si
        self.se = se
        self.is_scan = True

    def __repr__(self):
        return f"SDFF {self.q} <- D:{self.d}, SI:{self.si}, SE:{self.se}"


class Circuit:
    VALID_GATES = {"AND", "OR", "NAND", "NOR", "NOT", "XOR", "BUF", "BUFF"}

    def __init__(self):
        self.inputs = set()
        self.outputs = set()
        self.wires = set()

        self.gates = {}       # output -> Gate
        self.flipflops = []
        self.dffs = self.flipflops  # alias
        #: Q net -> clock net, for registers clocked by logic rather than the
        #: clock input (see VerilogParser._model_logic_clocks).
        self.logic_clocks = {}

        self.scan_inputs = set()
        self.scan_outputs = set()
        self.scan_enables = set()

        self.nodes = set()

    def _add_node(self, name):
        if name:
            self.nodes.add(name)

    def add_input(self, name):
        self.inputs.add(name)
        self._add_node(name)

    def add_output(self, name):
        self.outputs.add(name)
        self._add_node(name)

    def add_gate(self, gtype, output, inputs):
        gtype = gtype.upper()
        if gtype not in self.VALID_GATES:
            raise ValueError(f"Unsupported gate type: {gtype}")

        gate = Gate(gtype, output, inputs)
        self.gates[output] = gate

        self._add_node(output)
        for inp in inputs:
            self._add_node(inp)

    def add_flipflop(self, ff):
        self.flipflops.append(ff)
        self._add_node(ff.q)
        self._add_node(ff.d)
        if getattr(ff, 'is_scan', False):
            self._add_node(ff.si)
            self._add_node(ff.se)

    def all_signals(self):
        return self.nodes

    def promote_undefined_signals_to_inputs(self) -> list:
        """Treat a referenced-but-never-driven net as a free primary input.

        Some benchmark netlists (e.g. `s400.bench`/`s400.v`, where the
        clock-phase wire `Phi1H` is declared and used but never produced by
        any gate -- lost, presumably, when the original latch-based ISCAS-89
        circuit was flattened) reference a signal that is nobody's gate
        output, flip-flop Q, or declared input: a dangling/floating net.

        Left alone, that makes the net structurally indistinguishable from
        a genuine unbroken combinational feedback loop -- both simply never
        resolve during a topological pass -- which produces a misleading
        "combinational feedback loop" error for what is actually just an
        incomplete netlist. Promoting it to an ordinary primary input
        doesn't fabricate anything: an undriven net's real value is exactly
        as unconstrained as a primary input's.

        Returns the list of signal names promoted this way, so a caller can
        warn about them rather than silently reinterpreting the netlist.
        """
        referenced = set()
        for gate in self.gates.values():
            referenced.update(gate.inputs)
        for ff in self.flipflops:
            referenced.add(ff.d)

        defined = set(self.inputs) | set(self.gates.keys()) | {ff.q for ff in self.flipflops}
        undefined = sorted(referenced - defined)
        for name in undefined:
            self.add_input(name)
        return undefined

    def to_bench(self):
        """Converts the circuit to ISCAS .bench format."""
        lines = ["# Generated by PyATPG\n"]
        for inp in sorted(self.inputs):
            lines.append(f"INPUT({inp})")
        lines.append("")
        for out in sorted(self.outputs):
            lines.append(f"OUTPUT({out})")
        lines.append("")
        
        for out, gate in sorted(self.gates.items()):
            inputs_str = ", ".join(gate.inputs)
            lines.append(f"{out} = {gate.gtype}({inputs_str})")
            
        return "\n".join(lines)

    def to_verilog(self, module_name="circuit"):
        """Converts the circuit to simple structural Verilog format."""
        lines = [f"// Generated by PyATPG Trojan Dataset Generator"]
        
        # All I/O
        all_ports = sorted(list(self.inputs | self.outputs))
        lines.append(f"module {module_name} ({', '.join(all_ports)});")
        
        if self.inputs:
            lines.append(f"    input {', '.join(sorted(self.inputs))};")
        if self.outputs:
            lines.append(f"    output {', '.join(sorted(self.outputs))};")
            
        # Determine internal wires (nodes that are neither input nor output)
        internal_wires = [n for n in self.nodes if n not in self.inputs and n not in self.outputs]
        if internal_wires:
            # Chunk wires to avoid super long lines
            for i in range(0, len(internal_wires), 20):
                chunk = internal_wires[i:i+20]
                lines.append(f"    wire {', '.join(chunk)};")
                
        lines.append("")
        
        # Write gates
        for out, gate in sorted(self.gates.items()):
            gtype = gate.gtype.lower()
            # Standard Verilog gates: and, or, nand, nor, xor, not, buf
            if gtype == 'buff': 
                gtype = 'buf'
                
            inputs_str = ", ".join(gate.inputs)
            lines.append(f"    {gtype} g_{out} ({out}, {inputs_str});")
            
        lines.append("endmodule")
        return "\n".join(lines)

    def clone(self):
        """Returns a deep copy of the Circuit."""
        import copy
        return copy.deepcopy(self)



class NetlistParser:
    """
    Supports .bench / ISCAS-style netlists
    Example:
        G1 = AND(A, B)
        G2 = NOT(G1)
        G3 = DFF(G2)
    """

    def parse(self, text):
        c = Circuit()

        for line in text.splitlines():
            line = line.strip()

            if not line or line.startswith("#"):
                continue

            # INPUT
            if line.startswith("INPUT"):
                name = line[line.find("(")+1:line.find(")")]
                c.add_input(name)

            # OUTPUT
            elif line.startswith("OUTPUT"):
                name = line[line.find("(")+1:line.find(")")]
                c.add_output(name)

            # Assignment
            elif "=" in line:
                lhs, rhs = [x.strip() for x in line.split("=")]

                # DFF
                if rhs.startswith("DFF"):
                    arg = rhs[rhs.find("(")+1:rhs.find(")")]
                    ff = FlipFlop(lhs, arg)
                    c.add_flipflop(ff)

                # Gate
                else:
                    gtype = rhs[:rhs.find("(")].strip()
                    args = rhs[rhs.find("(")+1:rhs.find(")")]
                    inputs = [a.strip() for a in args.split(",")]

                    c.add_gate(gtype, lhs, inputs)

        return c
